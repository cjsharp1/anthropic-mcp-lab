/**
 * explain-exchange.ts — a prompt that teaches a format by example.
 *
 * Asks for a plain-language explanation of one MCP method, and
 * establishes the shape of the answer by including a worked example as
 * a prior turn.
 *
 * ---------------------------------------------------------------------------
 * What it teaches
 * ---------------------------------------------------------------------------
 *
 * Why a prompt returns MESSAGES rather than a string.
 *
 * `try_the_tools` returns one user message and could just as well have
 * been a template literal. This one cannot. It returns three turns —
 * user, assistant, user — where the middle one is an answer nobody
 * actually gave.
 *
 * That is a few-shot example, and it is the technique that makes the
 * prompt primitive worth having. A model shown one answer in the
 * desired shape will match it far more reliably than one told about
 * the shape in prose. Compare:
 *
 *   "Answer in three short sections with a one-line summary first"
 *
 * against an actual three-section answer sitting in the history. The
 * second wins, consistently, and it is only expressible because the
 * return type is a conversation rather than a paragraph.
 *
 * ---------------------------------------------------------------------------
 * The fabricated turn, and why it is honest
 * ---------------------------------------------------------------------------
 *
 * The assistant message below was never generated by a model. The
 * server is writing both halves of an exchange that did not happen and
 * handing it over as though it were history.
 *
 * That is normal, supported, and worth noticing anyway, because it is
 * the same mechanism as prompt injection. The difference is purely who
 * is doing it: here the server, which the user chose to connect, is
 * shaping its own suggested conversation. A client is free to show the
 * user exactly what it is about to insert — and a client that silently
 * drops fabricated history into a conversation without saying so is
 * one worth being wary of.
 *
 * The fabricated turn is kept short and factual for that reason. A
 * server that used this mechanism to install opinions, instructions or
 * claims about unrelated topics would be abusing a feature designed
 * for formatting, and nothing in the protocol would stop it.
 */

import { z } from "zod";
import { definePrompt } from "../types.js";

/**
 * The methods this prompt knows how to ask about.
 *
 * A closed set rather than free text, so the client can render a
 * dropdown and so the question is always about something that exists.
 * A model asked to explain `tools/frobnicate` will cheerfully invent
 * an answer, and a prompt that invites that is a prompt that produces
 * confident nonsense.
 */
const METHODS = [
  "initialize",
  "tools/list",
  "tools/call",
  "resources/read",
  "prompts/get",
  "notifications/progress",
] as const;

export const explainExchange = definePrompt({
  name: "explain_exchange",
  title: "Explain an MCP method",

  description:
    "Asks for a short, concrete explanation of one MCP method: what " +
    "it is for, what it carries, and what comes back. Includes a " +
    "worked example so the answer comes back in a consistent shape.",

  argsSchema: z.object({
    method: z
      .enum(METHODS)
      .describe("Which JSON-RPC method to explain."),
  }),

  build({ method }) {
    return [
      // Turn 1: the question, in the form the example answers.
      {
        role: "user",
        text:
          "Explain the MCP method `initialize` in three short " +
          "sections: what it is for, what it carries, and what comes " +
          "back. Start with a one-line summary.",
      },

      // Turn 2: the fabricated answer that sets the format. Short on
      // purpose — a long example costs tokens on every use and teaches
      // the shape no better than a brief one.
      {
        role: "assistant",
        text:
          "**The handshake that starts every MCP connection.**\n\n" +
          "*What it is for.* Agreeing terms before anything else " +
          "happens: which protocol revision both sides speak, and " +
          "what each supports.\n\n" +
          "*What it carries.* The client's protocol version, its name " +
          "and version, and the capabilities it offers the server.\n\n" +
          "*What comes back.* The version the server agreed to — " +
          "which may be older than the one asked for — plus the " +
          "server's own name, version and capabilities.",
      },

      // Turn 3: the real question, in the same shape as turn 1. The
      // parallel structure is what makes the example work; a third
      // turn phrased differently would weaken the pattern it is
      // there to establish.
      {
        role: "user",
        text:
          `Now explain the MCP method \`${method}\` in the same ` +
          "three sections, in the same style.",
      },
    ];
  },

  exampleWatch:
    "Three messages come back from one prompts/get, and the middle " +
    "one is an assistant turn the server wrote. That is the few-shot " +
    "example, and it is why prompts return messages rather than text.",
});
